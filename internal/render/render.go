// Package render turns a validated configuration and key material into the
// files both stacks run from. Rendering is pure and deterministic: the same
// inputs always produce byte-identical output.
package render

import (
	"bytes"
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"fmt"
	"io/fs"
	"sort"
	"strconv"
	"strings"
	"text/template"

	"github.com/xrvo/hearthgate/internal/config"
	"github.com/xrvo/hearthgate/internal/keys"
	"github.com/xrvo/hearthgate/internal/state"
)

// Paths of the rendered files, relative to the project directory.
const (
	HomeDir = "generated/home/"
	EdgeDir = "generated/edge/"
	EnvFile = ".env"
)

// ExampleConfig is the starting hearthgate.yml that `ctl init` writes when
// the project directory has none.
//
//go:embed templates/hearthgate.example.yml
var ExampleConfig []byte

//go:embed templates/*.tmpl
var templateFS embed.FS

var templates = template.Must(template.ParseFS(templateFS, "templates/*.tmpl"))

// File is one rendered file.
type File struct {
	Content []byte
	Mode    fs.FileMode
}

// Files maps a slash-separated path relative to the project directory to its content.
type Files map[string]File

// Paths returns the file paths in sorted order.
func (f Files) Paths() []string {
	paths := make([]string, 0, len(f))
	for p := range f {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	return paths
}

// WithPrefix returns the files under prefix, with the prefix removed.
func (f Files) WithPrefix(prefix string) Files {
	out := Files{}
	for p, file := range f {
		if rest, ok := strings.CutPrefix(p, prefix); ok {
			out[rest] = file
		}
	}
	return out
}

type data struct {
	*config.Config
	HomePrivate, HomePublic string
	EdgePrivate, EdgePublic string
	Preshared               string
	RedirectPort            string
	EdgeHash                string
	Images
}

// Images are the images the edge stack runs: linuxserver/wireguard for the
// tunnel, and nginx's official image for the proxy. The home stack's compose
// file names its own and passes them to ctl, so both sides match.
type Images struct {
	WireGuard string
	Nginx     string
}

// Owner is the user and group that own the generated files at home. The
// WireGuard container runs as them (PUID and PGID), so linuxserver's start-up
// finds nothing to chown on its read-only mount and does not warn about it.
type Owner struct{ UID, GID int }

// Render produces every generated file for both sides. owner may be nil when
// it is not known; the home compose file then falls back to its default.
//
// Each container gets a directory of its own, mounted read-only, so that the
// proxies beside a tunnel cannot read its keys.
func Render(cfg *config.Config, st *state.State, images Images, owner *Owner) (Files, error) {
	homePub, err := keys.Public(st.HomePrivate)
	if err != nil {
		return nil, fmt.Errorf("home key: %w", err)
	}
	edgePub, err := keys.Public(st.EdgePrivate)
	if err != nil {
		return nil, fmt.Errorf("edge key: %w", err)
	}
	d := data{
		Config:      cfg,
		HomePrivate: st.HomePrivate, HomePublic: homePub,
		EdgePrivate: st.EdgePrivate, EdgePublic: edgePub,
		Preshared: st.Preshared,
		Images:    images,
	}
	if cfg.HTTPSPort != 443 {
		d.RedirectPort = ":" + strconv.Itoa(cfg.HTTPSPort)
	}

	files := Files{}
	add := func(path, tmpl string, mode fs.FileMode) error {
		var buf bytes.Buffer
		if err := templates.ExecuteTemplate(&buf, tmpl, d); err != nil {
			return fmt.Errorf("render %s: %w", path, err)
		}
		files[path] = File{Content: buf.Bytes(), Mode: mode}
		return nil
	}

	steps := []struct {
		path, tmpl string
		mode       fs.FileMode
	}{
		{HomeDir + "tunnel/wg0.conf", "home-wg0.conf.tmpl", 0o600},
		{HomeDir + "tunnel/firewall.sh", "home-firewall.sh.tmpl", 0o644},
		{HomeDir + "caddy/Caddyfile", "home-Caddyfile.tmpl", 0o644},
		{HomeDir + "stream/nginx.conf", "home-nginx.conf.tmpl", 0o644},
		{EdgeDir + "tunnel/wg0.conf", "edge-wg0.conf.tmpl", 0o600},
		{EdgeDir + "tunnel/firewall.sh", "edge-firewall.sh.tmpl", 0o644},
		{EdgeDir + "proxy/nginx.conf", "edge-nginx.conf.tmpl", 0o644},
	}
	for _, s := range steps {
		if err := add(s.path, s.tmpl, s.mode); err != nil {
			return nil, err
		}
	}

	// The hashes change whenever a mounted file changes, which is what makes
	// `docker compose up -d` recreate the containers that read them.
	d.EdgeHash = files.WithPrefix(EdgeDir).Hash()
	if err := add(EdgeDir+"docker-compose.yml", "edge-compose.yml.tmpl", 0o644); err != nil {
		return nil, err
	}

	lines := []string{
		"# Generated by Hearthgate. Do not edit: change hearthgate.yml and run `ctl apply`.",
		"HEARTHGATE_CONFIG_HASH=" + files.WithPrefix(HomeDir).Hash(),
		"HEARTHGATE_DMZ_SUBNET=" + cfg.DMZSubnet.String(),
		"HEARTHGATE_DMZ_IP=" + cfg.DMZIP.String(),
		"HEARTHGATE_DMZ_RANGE=" + cfg.DMZRange.String(),
		"HEARTHGATE_MGMT_SUBNET=" + cfg.MgmtSubnet.String(),
		"HEARTHGATE_MGMT_IP=" + cfg.MgmtIP.String(),
		"HEARTHGATE_MGMT_RANGE=" + cfg.MgmtRange.String(),
	}
	if owner != nil {
		lines = append(lines,
			"HEARTHGATE_PUID="+strconv.Itoa(owner.UID),
			"HEARTHGATE_PGID="+strconv.Itoa(owner.GID))
	}
	env := strings.Join(append(lines, ""), "\n")
	files[EnvFile] = File{Content: []byte(env), Mode: 0o644}

	return files, nil
}

// Hash identifies the content of a set of files.
func (files Files) Hash() string {
	h := sha256.New()
	for _, p := range files.Paths() {
		fmt.Fprintf(h, "%s\x00%d\x00", p, len(files[p].Content))
		h.Write(files[p].Content)
	}
	return hex.EncodeToString(h.Sum(nil))[:16]
}
